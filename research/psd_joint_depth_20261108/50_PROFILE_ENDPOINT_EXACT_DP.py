#!/usr/bin/env python3
"""Exact rational O(d*nu^2) DP for sharp PSD recovery exponent endpoint
at fixed target nullity and facial-reduction degree (checkpoint 49).
The matching harmonic PSD graph is generated by checkpoint 46.
"""
from functools import lru_cache
from fractions import Fraction as F

@lru_cache(None)
def prefix(j, budget):
    """Minimum nested resistance for layers 2,...,j at total budget."""
    if budget<j-1: return None
    if j==2: return F(1,2**budget-1),(budget,)
    best=None
    for last in range(1,budget-(j-2)+1):
        old=prefix(j-1,budget-last)
        if old is None:continue
        resistance=(1+old[0])/F(2**last-1)
        if best is None or resistance<best[0]:
            best=(resistance,old[1]+(last,))
    return best

def exact_endpoint(nullity,degree):
    assert nullity>=degree>=2
    if degree==2:return F(1,2),(1,nullity-1)
    budget=nullity-1 # first exposing rank is always one at the optimum
    best=None
    for last in range(1,budget-(degree-2)+1):
        old=prefix(degree-1,budget-last)
        if old is None:continue
        resistance=old[0]/2**last
        if best is None or resistance<best[0]:
            best=(resistance,(1,)+old[1]+(last,))
    return F(1,2)/(1+best[0]),best[1]

def profile_formula(s):
    d=len(s); assert d>=2 and all(a>=1 for a in s)
    p={1:1}
    for j in range(2,d+1): p[j]=p[j-1]*(2**s[j-1]-1)
    return F(2**(s[-1]-1)*p[d-1],sum(p.values()))

def positive_compositions(total,parts):
    if parts==1:yield (total,)
    else:
        for first in range(1,total-parts+2):
            for tail in positive_compositions(total-first,parts-1):
                yield (first,)+tail

def test():
    count=0
    for nu in range(2,11):
        for d in range(2,nu+1):
            val,who=exact_endpoint(nu,d)
            assert profile_formula(who)==val
            brute=max((profile_formula(s),s) for s in positive_compositions(nu,d))
            assert val==brute[0],(nu,d,val,brute)
            count+=1
    print(f'PASS {count} exact DP vs exhaustive positive compositions (nullity <=10)')
    for nu in range(3,9):
        print(nu,[(d,str(exact_endpoint(nu,d)[0]),
                        exact_endpoint(nu,d)[1]) for d in range(3,nu+1)])

if __name__=='__main__':test()
